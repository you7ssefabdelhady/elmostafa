function getCategoryName(catId) {
  const cat = CATEGORIES.find((c) => c.id === catId);
  return cat ? cat.name : "";
}

function getProductById(id) {
  return PRODUCTS.find((p) => p.id === id);
}

/* رسالة واتساب جاهزة للاستفسار عن سعر منتج معيّن */
function buildInquiryMessage(product) {
  const msg = `مرحبًا ${SITE_CONFIG.brandName}، حابب أستفسر عن سعر: ${product.name} 🙏`;
  return encodeURIComponent(msg);
}

function inquiryWhatsAppUrl(product) {
  return `https://wa.me/${SITE_CONFIG.whatsappNumber}?text=${buildInquiryMessage(product)}`;
}
